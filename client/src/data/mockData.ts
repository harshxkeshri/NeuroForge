// 7-day and 30-day Price Trend Intelligence Generator
export function getPriceTrendStats(cropId: string, mandiId?: string): PriceTrendStats {
  const crop = CROPS.find(c => c.id === cropId) || CROPS[0];
  const targetMandi = MANDIS.find(m => m.id === mandiId && m.cropId === cropId) ||
    MANDIS.find(m => m.cropId === cropId) ||
    MANDIS[0];

  const basePrice = targetMandi.pricePerKg;

  // Realistic 7-day price fluctuations
  const historyDeltas = [-1.2, -0.6, 0.4, -0.2, 0.8, 1.1, 0];
  const dates = ['6d ago', '5d ago', '4d ago', '3d ago', '2d ago', 'Yesterday', 'Today'];

  const historical = dates.map((dateLabel, idx) => {
    const price = Number((basePrice + historyDeltas[idx]).toFixed(2));
    return {
      date: dateLabel,
      price,
      mandi: targetMandi.mandiName,
      type: 'actual' as const,
    };
  });

  // Simple moving average 3-day projected trend
  const last3Avg = (historical[4].price + historical[5].price + historical[6].price) / 3;
  const projection = [
    { date: 'Today', price: historical[6].price, mandi: targetMandi.mandiName, type: 'actual' as const },
    { date: 'Tomorrow (Est.)', price: Number((last3Avg + 0.3).toFixed(2)), mandi: targetMandi.mandiName, type: 'predicted' as const },
    { date: '+2 Days (Est.)', price: Number((last3Avg + 0.5).toFixed(2)), mandi: targetMandi.mandiName, type: 'predicted' as const },
  ];

  const prices = historical.map(h => h.price);
  const highestPrice = Math.max(...prices);
  const lowestPrice = Math.min(...prices);
  const sevenDayAvg = Number((prices.reduce((a, b) => a + b, 0) / prices.length).toFixed(2));
  const percentageChange = Number((((prices[prices.length - 1] - prices[0]) / prices[0]) * 100).toFixed(1));

  const volatility = Math.abs(percentageChange) > 8 ? 'High' : Math.abs(percentageChange) > 3 ? 'Moderate' : 'Low';

  return {
    cropId: crop.id,
    cropName: crop.cropName,
    mandiName: targetMandi.mandiName,
    currentPrice: prices[prices.length - 1],
    sevenDayAvg,
    highestPrice,
    lowestPrice,
    percentageChange,
    volatility,
    historical,
    projection,
  };
}
